"""Export the fixed demo text as outlines using Unity's saved TMP settings.

Run from the demo: python scripts/export-content-text.py <Unity project root>
Requires fontTools. Font files stay in the Unity project; CI uses exported SVGs.
"""
import html
import json
from pathlib import Path
import re
import sys

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

demo = Path(__file__).resolve().parents[1]
sys.stdout.reconfigure(encoding='utf8')
unity = Path(sys.argv[1]).resolve()
scene = (unity / 'Assets/_2ndStudies/1.Proactive/Scenes/Proactive.unity').read_text('utf-8-sig')
objects = {int(i): (int(t), b) for t, i, b in re.findall(r'--- !u!(\d+) &(\d+)\n(.*?)(?=\n--- !u!|\Z)', scene, re.S)}


def field(body, name):
    return re.search(r'^  ' + name + r': (.*)', body, re.M)[1]


def number(body, name):
    return float(re.search(r'\b' + name + r': ([-\d.eE]+)', body)[1])


def plain(value):
    return ' '.join(re.sub(r'<[^>]+>', '', value).split())


rects = {i: b for i, (kind, b) in objects.items() if kind == 224}
rect_by_go = {int(re.search(r'm_GameObject: \{fileID: (\d+)', b)[1]): b for b in rects.values()}


def names(body):
    go = int(re.search(r'm_GameObject: \{fileID: (\d+)', body)[1])
    parent = int(re.search(r'm_Father: \{fileID: (\d+)', rect_by_go[go])[1])
    return [field(objects[go][1], 'm_Name')] + (names(rects[parent]) if parent in rects else [])


texts = {}
for kind, body in objects.values():
    if kind != 114 or '\n  m_text:' not in body:
        continue
    ancestors = names(body)
    if 'ResultContent' in ancestors or not any(name in ancestors for name in ['ArticleContent', 'BookingContent']):
        continue
    raw = re.search(r'^  m_text: (.*?)(?=\n  m_)', body, re.S | re.M)[1]
    raw = ' '.join(raw.split())
    if raw.startswith('"'):
        # Unrelated labels can contain YAML-only escapes; these exports use JSON-compatible strings.
        try:
            raw = json.loads(raw)
        except json.JSONDecodeError:
            continue
    texts[plain(raw)] = (raw, body)

fonts = {}
for filename in ['MarkPro', 'Mark-Pro-Medium', 'Mark-Pro-Bold']:
    folder = unity / 'Assets/TextMesh Pro/Fonts'
    asset = (folder / (filename + ' SDF.asset')).read_text('utf-8-sig')
    guid = re.search(r'guid: (\w+)', (folder / (filename + ' SDF.asset.meta')).read_text())[1]
    font = TTFont(folder / (filename + '.ttf'))
    glyphs = {}
    for index, metrics in re.findall(r'  - m_Index: (\d+)\n    m_Metrics:\n(.*?)(?=    m_GlyphRect:)', asset, re.S):
        glyphs[int(index)] = number(metrics, 'm_HorizontalAdvance')
    chars = {int(u): int(g) for u, g in re.findall(r'm_Unicode: (\d+)\n    m_GlyphIndex: (\d+)', asset)}
    pairs = {}
    for pair in re.findall(r'- m_FirstAdjustmentRecord:(.*?)(?=\n    - m_FirstAdjustmentRecord:|\n  m_\w|\Z)', asset, re.S):
        first, second = pair.split('m_SecondAdjustmentRecord:')
        pairs[(int(number(first, 'm_GlyphIndex')), int(number(second, 'm_GlyphIndex')))] = (number(first, 'm_XAdvance'), number(second, 'm_XAdvance'))
    fonts[guid] = (font, asset, glyphs, chars, pairs)

output = demo / 'public/content/text'
output.mkdir(parents=True, exist_ok=True)
css = ['/* Generated by scripts/export-content-text.py from the saved Unity scene. */',
       '[data-unity-text] { color: transparent !important; background-repeat: no-repeat; background-position: 0 0; background-size: 100% 100%; }']
report = []
source = (demo / 'index.html').read_text('utf8')
for key, encoded in re.findall(r'data-unity-text="([^"]+)"[^>]*>([^<]+)<', source):
    text = html.unescape(encoded)
    raw, body = texts[plain(text)]
    guid = re.search(r'm_fontAsset: \{fileID: \d+, guid: (\w+)', body)[1]
    font, asset, advances, chars, pairs = fonts[guid]
    go = int(re.search(r'm_GameObject: \{fileID: (\d+)', body)[1])
    rect = next(b for k, b in objects.values() if k == 224 and f'm_GameObject: {{fileID: {go}}}' in b)
    size = number(body, 'm_fontSize')
    box = field(rect, 'm_SizeDelta')
    width, height = number(box, 'x'), number(box, 'y')
    tracking = number(body, 'm_characterSpacing') * size * .01
    scale = size / number(asset, 'm_PointSize')
    line_tag = re.search(r'<line-height=([\d.]+)>', raw)
    line_height = float(line_tag[1]) if line_tag else number(asset, 'm_LineHeight') * scale
    glyphset = font.getGlyphSet()
    cmap = font.getBestCmap()
    outline_scale = size / font['head'].unitsPerEm

    def layout(line):
        x, placed = 0, []
        for i, char in enumerate(line):
            glyph = chars[ord(char)]
            before = pairs.get((chars[ord(line[i-1])], glyph), (0, 0))[1] if i else 0
            after = pairs.get((glyph, chars[ord(line[i+1])]), (0, 0))[0] if i + 1 < len(line) else 0
            placed.append((char, x))
            x += (advances[glyph] + before + after) * scale + tracking
        return placed, x - tracking

    lines = ['']
    for word in text.split():
        candidate = (lines[-1] + ' ' + word).lstrip()
        if lines[-1] and layout(candidate)[1] > width and int(number(body, 'm_TextWrappingMode')) != 0:
            lines.append(word)
        else:
            lines[-1] = candidate
    bounds = BoundsPen(glyphset)
    for char, x in layout(lines[0])[0]:
        glyphset[cmap[ord(char)]].draw(TransformPen(bounds, (outline_scale, 0, 0, outline_scale, x, 0)))
    margin_top = number(field(body, 'm_margin'), 'y')
    if int(number(body, 'm_VerticalAlignment')) == 4096:
        baseline = (height + bounds.bounds[1] + bounds.bounds[3]) / 2
    else:
        baseline = number(asset, 'm_AscentLine') * scale + margin_top
    pen = SVGPathPen(glyphset, ntos=lambda value: f'{value:.3f}'.rstrip('0').rstrip('.') if value else '0')
    for row, line in enumerate(lines):
        for char, x in layout(line)[0]:
            glyphset[cmap[ord(char)]].draw(TransformPen(pen, (outline_scale, 0, 0, -outline_scale, x, baseline + row * line_height)))
    color = field(body, 'm_fontColor')
    fill = '#000' if number(color, 'r') == 0 else '#b6c7dd' if key == 'composer-placeholder' else '#fff'
    # ArticleBody's SDF face dilation, approximated as a small outline expansion.
    stroke = .08 * .9 * 10 * scale if key in ['article-intro', 'article-second-body', 'article-last-body'] else 0
    svg = f'<svg xmlns="http://www.w3.org/2000/svg" width="{width:g}" height="{height:g}" viewBox="0 0 {width:g} {height:g}"><path fill="{fill}" stroke="{fill}" stroke-width="{stroke:.4f}" stroke-linejoin="round" d="{pen.getCommands()}"/></svg>\n'
    (output / (key + '.svg')).write_text(svg, encoding='utf8')
    css.append(f'[data-unity-text="{key}"] {{ width: {width:g}px; height: {height:g}px; font-size: {size:g}px; line-height: {line_height:g}px; letter-spacing: {tracking:g}px; background-image: url("/content/text/{key}.svg"); }}')
    report.append({'key': key, 'size': size, 'lineHeight': line_height, 'tracking': tracking, 'baseline': round(baseline, 4), 'lines': lines})
(demo / 'src/content-text.css').write_text('\n'.join(css) + '\n', encoding='utf8')
print(json.dumps(report, ensure_ascii=False, indent=2))
